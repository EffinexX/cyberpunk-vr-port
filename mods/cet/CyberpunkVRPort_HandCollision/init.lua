-- Bone poses, read once per bone per frame: the riding sets and the obstacle lists touch the same bones several
-- times a frame, and every VRBoneModelPos/Rot call crosses into the plugin and hands back fresh userdata.
local BPX, BPY, BPZ, BQI, BQJ, BQK, BQR, BGEN, BOK = {}, {}, {}, {}, {}, {}, {}, {}, {}
local gen = 0

local function bone(idx)
    if BGEN[idx] == gen then
        if not BOK[idx] then return nil end
        return BPX[idx], BPY[idx], BPZ[idx], BQI[idx], BQJ[idx], BQK[idx], BQR[idx]
    end
    BGEN[idx] = gen
    local p = VRBoneModelPos(idx)
    local q = VRBoneModelRot(idx)
    if not p or p.w < 0.5 or not q then BOK[idx] = false return nil end
    BOK[idx] = true
    BPX[idx], BPY[idx], BPZ[idx] = p.x, p.y, p.z
    BQI[idx], BQJ[idx], BQK[idx], BQR[idx] = q.i, q.j, q.k, q.r
    return BPX[idx], BPY[idx], BPZ[idx], BQI[idx], BQJ[idx], BQK[idx], BQR[idx]
end

local function qrot(qi, qj, qk, qr, x, y, z)
    local tx = 2.0 * (qj * z - qk * y)
    local ty = 2.0 * (qk * x - qi * z)
    local tz = 2.0 * (qi * y - qj * x)
    return x + qr * tx + (qj * tz - qk * ty),
           y + qr * ty + (qk * tx - qi * tz),
           z + qr * tz + (qi * ty - qj * tx)
end

