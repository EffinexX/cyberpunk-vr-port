-- CyberpunkVRPort — the hands, their FINGERS, and the weapon they hold all stop at the body and at each other.
--
-- WHY NOT PHYSICS. Every collider involved is Kinematic: the body capsules, the hand capsules, the weapon's
-- cooked bodies. A kinematic body pushes DYNAMIC objects -- which is why props and the ball work -- but nothing
-- pushes it, and two kinematic bodies do not interact at all. Masks decide whether a contact is generated;
-- simulationType decides whether anything MOVES. Dynamic is not available either, measured three ways:
-- authored Dynamic the capsule is not held by its bone binding and fell to Z = -8100; flipped live the flip is
-- ONE-WAY (kin=1 while 1519 m away at 110 m/s); and SetTransform is inert -- four different local positions all
-- left the world bounds identical.
--
-- So the hand is stopped by moving the arm solver's TARGET. Verified end to end: a forced 10 cm hold put the
-- solved palm exactly 0.080 m below the tracked target -- the commanded 0.10 minus the then-0.02 deadband. An
-- earlier attempt did nothing because the clamp sat before the gizmo path, which recomputes target[0..2]; it now
-- runs immediately before VRIK_SolveArm. And the bone snapshot only exists while SetVRDiagCapture is on, which is
-- why the attempt before that found no capsules at all.
--
-- WHAT MOVES, AND WHAT THAT MEANS. The only handle is the wrist target, so the thing being solved is a RIGID
-- TRANSLATION of everything that rides that wrist: the palm, all fifteen phalanges, and every capsule of the
-- weapon in that hand. Press the muzzle into your chest and the whole gun slides back rather than pivoting about
-- the grip -- a real gun would rotate, but rotation is not ours to give, and a slide is the honest approximation.
-- A fingertip stopping the hand is the same statement: the arm cannot reach further because a finger is against
-- something, so the wrist ends up where that finger's contact leaves it.
--
-- THE GEOMETRY IS NOT RETYPED HERE. capsules.lua is generated by tools/emit_hand_collision_data.py from the very
-- SEGMENTS and FINGER_SEGMENTS tables that write the .ent, placement rules included. So what stops a hand and
-- what a ball bounces off cannot disagree.
--
-- The PALM is deliberately a different size for the two jobs, and the generator holds both numbers with the
-- reason. For props the collider is a 0.16 m tube down the whole hand -- a ball should bounce off a hand, not
-- fall between its fingers. Here the fingers exist, and a 0.16 m tube with a 31 mm radius swallows every one of
-- them, which is why fingers "did not collide" even once they were in the table. So the clamp gets the rigid palm
-- instead: 0.0814 m, the measured wrist-to-Middle1 distance.
--
-- EVERYTHING IS MODEL SPACE: bones come from VRBoneModelPos/Rot there, and VRHandRawModel / VRHandStopModel keep
-- the target there, so no frame conversion happens anywhere.
--
-- ============================================================================================================
-- THE SHAKE, AND EVERY CAUSE IT TURNED OUT TO HAVE
--
-- Five rounds of "it still twitches", five different causes. Worth listing, because four of them look identical
-- in the headset and none of them was noise:
--
--   1. FEEDBACK. The resolved position is a function of the obstacle geometry, and some of that geometry is
--      placed by the very solve this target drives. vrp_arm_<side> was an obstacle for its own hand, and
--      VRIK_SolveArm places the upper arm, forearm AND hand from one target, so pushing the hand swept the
--      shoulder capsule. Also: a shape oriented by the solved bone, and the holder chosen per frame as "nearer
--      wrist" -- a coin flip at the grip, and each flip swapped which hand was frozen.
--   2. A CAPSULE THAT WAS NOT THE GUN. The frame bone's fit came out as a 0.0725 m radius ball at the grip,
--      against a weapon 0.027 half-thick, so the free hand was shoved 0.113 m clear of the pistol. Fixed in the
--      decomposition (tools/emit_weapon_collision_data.py), not here.
--   3. WINNER-TAKES-ALL. Applying only the deepest contact per pass made the answer depend on which of a dozen
--      contacts won, and the winner changed every frame: the hold jumped between 0.042 and 0.113 m.
--   4. AVERAGING. Fixed the jump but divided the correction by the contact count, so the stop got softer the
--      more capsules were involved -- twenty at a gun -- and the hand sank through, seen as
--      "collision comes and goes". Sequential projection is count-independent and is what runs now.
--   5. GARBAGE COLLECTION. With none of the above left, the timing said mean 2.36 ms, worst mean 4.38, and
--      single frames at 16-22 ms with only 19 pairs in them. At 45 fps the whole frame is 22 ms, so those were
--      dropped frames, and a dropped frame reads as a twitch on whatever you are looking at. The cause was this
--      module allocating roughly a thousand tables a frame -- a capsule record plus two endpoint tables each, a
--      table per candidate pair, and a CONCATENATED STRING key per pair. Everything below is pooled and flat for
--      that reason: capsules are tables of scalars taken from a pool, the candidate list is parallel arrays, and
--      contact keys are integers.
--
-- The ORDER of the two solves keeps the weapon out of the feedback. The holder resolves first, from its RAW
-- wrist, against the body -- a pure function of tracking. The free hand resolves second, against the gun placed
-- where the holder's solve just put it. One direction, no cycle. The free hand never displaces the holder: it
-- sees the holder's hand and gun as immovable, which is also what a hand pressing on a braced gun feels like.
--
-- Plus one thing that was not a shake but made all of them worse: the plugin's 0.02 m deadband applied only
-- (len - dead)/len of the hold, so a 3 cm push became 1 cm and the drawn hand always sat up to 2 cm INSIDE
-- whatever stopped it. That belongs to the abandoned velocity-driven design, where a driven body genuinely
-- trailed its target. This resolution is analytic and exact, so the deadband is pure error.
-- ============================================================================================================

